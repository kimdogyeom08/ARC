CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL,
  username_key TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE builds
  ADD COLUMN IF NOT EXISTS user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
  ADD COLUMN IF NOT EXISTS skill_order TEXT[] NOT NULL DEFAULT '{}',
  ADD COLUMN IF NOT EXISTS items TEXT[] NOT NULL DEFAULT '{}';

CREATE INDEX IF NOT EXISTS builds_user_created_at_desc_idx ON builds (user_id, created_at DESC);
